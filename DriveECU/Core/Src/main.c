/* USER CODE BEGIN 4 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance != TIM2) return;

    tx_data[4] = (uint8_t)(tx_count >> 24);
    tx_data[5] = (uint8_t)(tx_count >> 16);
    tx_data[6] = (uint8_t)(tx_count >> 8);
    tx_data[7] = (uint8_t)(tx_count);
    tx_count++;

    if (HAL_CAN_AddTxMessage(&hcan1, &tx_header, tx_data, &tx_mailbox) == HAL_OK) {
        HAL_GPIO_TogglePin(LD2_GPIO_Port, LD2_Pin);
    }
}

void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan)
{
    HAL_CAN_GetRxMessage(hcan, CAN_RX_FIFO0, &rx_header, rx_data);

    if (rx_header.StdId == ISOTP_RX_CAN_ID) {
        isotp_can_rx(rx_data, (uint8_t)rx_header.DLC);
        return;
    }

    printf("[RX] ID:0x%03lX DLC:%lu Data:%02X %02X %02X %02X cnt:%lu\r\n",
           rx_header.StdId, rx_header.DLC,
           rx_data[0], rx_data[1], rx_data[2], rx_data[3],
           (uint32_t)(rx_data[1] << 24 | rx_data[2] << 16 | rx_data[3] << 8 | rx_data[4]));
}
